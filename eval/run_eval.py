"""Measure verdict accuracy on labelled claims.

  python -u eval/run_eval.py dev        tune on this split
  python -u eval/run_eval.py holdout    report this split; do not tune on it

Images are AI-generated by Muse Image and were checked by eye, so scores say nothing yet about real phone photos.
Add your own photos through cases_extra.json (same fields as build_cases output).
"""
import json
import sys
import time
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from claimcheck_core import agent, rules
from claimcheck_core import meta_api as api

HERE = Path(__file__).parent
EXCLUDED = {"feat03"}  # the generated image is not recognisably a backpack
WRONG_COMPOSITION = "100% cotton"
WRONG_ORIGIN = "Germany"
WRONG_COLOR = {"red": "blue", "navy": "red", "green": "black", "black": "white", "white": "black",
               "yellow": "green", "grey": "pink", "pink": "grey"}


def build_cases() -> list[dict]:
    cases = []
    def add(scene, check, claimed, concept, text, expected):
        cases.append({"image": scene["id"], "check": check, "claimed": str(claimed), "concept": concept,
                      "text": text, "expected": expected})
    for s in json.loads((HERE / "scenes.json").read_text(encoding="utf-8")):
        if s["id"] in EXCLUDED:
            continue
        if s["kind"] == "label":
            add(s, "composition", s["composition"], "care label", s["composition"], rules.VERIFIED)
            wrong = "80% acrylic 20% wool" if s["composition"] == WRONG_COMPOSITION else WRONG_COMPOSITION
            add(s, "composition", wrong, "care label", wrong, rules.CONTRADICTED)
            add(s, "text", s["origin"], "care label", f"Made in {s['origin']}", rules.VERIFIED)
            add(s, "text", WRONG_ORIGIN, "care label", f"Made in {WRONG_ORIGIN}", rules.CONTRADICTED)
        elif s["kind"] == "count":
            add(s, "count", s["count"], s["concept"], f"Set of {s['count']}", rules.VERIFIED)
            add(s, "count", s["count"] + 1, s["concept"], f"Set of {s['count'] + 1}", rules.CONTRADICTED)
        elif s["kind"] == "color":
            add(s, "color", s["color"], s["concept"], f"{s['color']} {s['concept']}", rules.VERIFIED)
            w = WRONG_COLOR[s["color"]]
            add(s, "color", w, s["concept"], f"{w} {s['concept']}", rules.CONTRADICTED)
        elif s["kind"] == "feature":
            add(s, "visual", s["feature"], s["concept"], f"Has {s['feature']}",
                rules.VERIFIED if s["truth"] else rules.CONTRADICTED)
        elif s["kind"] == "hidden":
            add(s, "composition", "100% cotton", "care label", "100% cotton", rules.NOT_VISIBLE)
    extra = HERE / "cases_extra.json"
    if extra.exists():
        cases += json.loads(extra.read_text(encoding="utf-8"))
    return cases


def in_split(image: str, split: str) -> bool:
    is_dev = sum(map(ord, image)) % 3 == 0
    return is_dev if split == "dev" else not is_dev


def run_case(case: dict) -> dict:
    session = agent.Session(listing="")
    claim = agent.Claim(id="c1", text=case["text"], attribute="", check=case["check"], claimed=case["claimed"],
                        sam_concept=case["concept"], shot_request="", attempts=1)
    jpeg = (HERE / "images" / f"{case['image']}.jpg").read_bytes()
    t0 = time.time()
    try:
        _, _, results = agent._inspect_concept(session, case["concept"], [claim], jpeg)
        r = results["c1"]
    except Exception as e:  # counted, never hidden
        r = {"verdict": "error", "rule": type(e).__name__, "detail": str(e)[:200], "observed": ""}
    return {**case, "got": r["verdict"], "rule": r["rule"], "detail": r["detail"], "observed": r.get("observed", ""),
            "seconds": round(time.time() - t0, 1), "usd": session.cost()}


def main(split: str):
    cases = [c for c in build_cases() if in_split(c["image"], split)]
    print(f"{split}: {len(cases)} claims", flush=True)
    results = []
    with ThreadPoolExecutor(6) as pool:
        for r in pool.map(run_case, cases):
            results.append(r)
            mark = "ok " if r["got"] == r["expected"] else "BAD"
            print(mark, r["image"], r["check"], repr(r["claimed"]), "exp", r["expected"], "got", r["got"],
                  "|", r["rule"], "|", r["observed"][:70], flush=True)

    total = len(results)
    correct = sum(r["got"] == r["expected"] for r in results)
    tp = sum(r["got"] == rules.CONTRADICTED and r["expected"] == rules.CONTRADICTED for r in results)
    fp = sum(r["got"] == rules.CONTRADICTED and r["expected"] != rules.CONTRADICTED for r in results)
    fn = sum(r["got"] != rules.CONTRADICTED and r["expected"] == rules.CONTRADICTED for r in results)
    secs = sorted(r["seconds"] for r in results)
    summary = {
        "split": split, "claims": total, "images": len({r["image"] for r in results}),
        "accuracy": round(correct / total, 3),
        "contradiction_precision": round(tp / (tp + fp), 3) if tp + fp else None,
        "contradiction_recall": round(tp / (tp + fn), 3) if tp + fn else None,
        "false_contradictions": fp, "missed_contradictions": fn,
        "by_check": {k: f"{sum(r['got'] == r['expected'] for r in results if r['check'] == k)}/{v}"
                     for k, v in Counter(r["check"] for r in results).items()},
        "median_seconds_per_claim": secs[len(secs) // 2],
        "usd_total": round(sum(r["usd"] for r in results), 4),
    }
    (HERE / f"results_{split}.json").write_text(
        json.dumps({"summary": summary, "results": results}, ensure_ascii=False, indent=1), encoding="utf-8")
    print(json.dumps(summary, indent=1), flush=True)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "dev")
