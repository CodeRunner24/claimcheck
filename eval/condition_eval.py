"""Does the camera flag damage, and leave clean products alone?

  python -u eval/condition_eval.py

Damaged images are generated by Muse Image and were checked by eye. Clean images are the real Commons photos that
real_eval.py uses, chosen because no damage is visible at this size. (p159 was first in this set, was flagged for rust, and on a
second look really is rusty, so the label was wrong and it was removed.) A small check of a feature that only ever suggests:
the seller confirms or dismisses each flag.
"""
import json
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from claimcheck_core import agent, finishing, meta_api as api, vision

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

HERE = Path(__file__).parent
FOLDER = HERE / "images_condition"
DAMAGED = {
    "tshirt_hole": "Phone photo of a plain grey t-shirt laid flat on a table, with one clearly visible ragged hole in the chest. No text.",
    "tshirt_stain": "Phone photo of a plain white t-shirt laid flat on a table, with one large obvious brown coffee stain on the front. No text.",
    "mug_chip": "Phone photo of a plain white ceramic mug on a table, with a large obvious chip broken out of the rim. No text.",
    "shoe_tear": "Phone photo of a single leather shoe on a floor, with a long obvious tear in the side. No text.",
    "bag_rip": "Phone photo of a blue backpack on a floor, with a large obvious rip in the front pocket. No text.",
    "jacket_stain": "Phone photo of a beige jacket laid flat, with a large obvious dark oil stain on the sleeve. No text.",
}
CLEAN = {"p152": "mug", "p154": "mug", "p143": "backpack", "p146": "backpack", "p081": "shoe", "p176": "shoe", "p139": "backpack"}


def run(item):
    name, path, concept, damaged = item
    jpeg = vision.prepare_image(path.read_bytes())
    session = agent.Session()
    instances = vision.parse_sam(api.sam_raw(concept, jpeg, session.trace))
    if not instances:
        return {"name": name, "damaged": damaged, "skipped": "SAM found nothing", "usd": session.cost()}
    session.hero_source = (jpeg, instances, 1)
    finishing.notice_condition(session)
    flags = [c.observed for c in session.claims if c.source == "noticed"]
    return {"name": name, "damaged": damaged, "flags": flags, "usd": session.cost()}


def main():
    FOLDER.mkdir(exist_ok=True)
    items = []
    for name, prompt in DAMAGED.items():
        path = FOLDER / f"{name}.jpg"
        if not path.exists():
            path.write_bytes(api.generate_image(prompt, purpose="condition test image"))
        items.append((name, path, {"tshirt": "t-shirt", "mug": "mug", "shoe": "shoe", "bag": "backpack", "jacket": "jacket"}[name.split("_")[0]], True))
    items += [(name, HERE / "images_real" / f"{name}.jpg", concept, False) for name, concept in CLEAN.items()]
    with ThreadPoolExecutor(6) as pool:
        rows = list(pool.map(run, items))
    for r in rows:
        print(r["name"], "damaged" if r["damaged"] else "clean", r.get("flags", r.get("skipped")), flush=True)
    done = [r for r in rows if "flags" in r]
    summary = {"damaged": sum(r["damaged"] for r in done), "damaged_flagged": sum(r["damaged"] and bool(r["flags"]) for r in done),
               "clean": sum(not r["damaged"] for r in done), "clean_wrongly_flagged": sum((not r["damaged"]) and bool(r["flags"]) for r in done),
               "skipped": len(rows) - len(done), "usd_total": round(sum(r["usd"] for r in rows), 3)}
    (HERE / "results_condition.json").write_text(json.dumps({"summary": summary, "rows": rows}, ensure_ascii=False, indent=1), encoding="utf-8")
    print(json.dumps(summary), flush=True)


if __name__ == "__main__":
    main()
